export const LEVELS = [
  { id: "seedling", name: "Seedling", emoji: "🌱", min: 0 },
  { id: "sprout", name: "Sprout", emoji: "🌿", min: 500 },
  { id: "guardian", name: "Green Guardian", emoji: "🌳", min: 1500 },
  { id: "champion", name: "Climate Champion", emoji: "🌍", min: 4000 },
];

export function levelFor(points) {
  let current = LEVELS[0];
  LEVELS.forEach((l) => {
    if (points >= l.min) current = l;
  });
  const next = LEVELS[LEVELS.indexOf(current) + 1] || null;
  const span = next ? next.min - current.min : 1;
  const progress = next ? Math.min(100, ((points - current.min) / span) * 100) : 100;
  return { ...current, next, progress, toNext: next ? Math.max(0, next.min - points) : 0 };
}
